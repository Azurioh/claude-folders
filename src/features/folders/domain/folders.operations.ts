/**
 * Pure, immutable updates of one project's folder tree.
 *
 * Every operation returns an {@link OperationResult}: `{ ok: true, state }` carrying a new state,
 * or `{ ok: false, reason }` when the request is invalid (blank name, unknown id, forbidden move).
 * Operations never throw and never mutate the state they receive.
 */
import type {
  ConversationId,
  FiledConversation,
  Folder,
  FolderId,
  ProjectFolders,
  Section,
} from '@/features/folders/domain/folders.model';
import { isInside } from '@/features/folders/domain/folders.queries';

export type RejectionReason =
  | 'empty-name'
  | 'empty-title'
  | 'folder-not-found'
  | 'folder-id-taken'
  | 'conversation-not-found'
  | 'invalid-move';

export type OperationResult =
  | { readonly ok: true; readonly state: ProjectFolders }
  | { readonly ok: false; readonly reason: RejectionReason };

function accepted(state: ProjectFolders): OperationResult {
  return { ok: true, state };
}

function rejected(reason: RejectionReason): OperationResult {
  return { ok: false, reason };
}

function withFolder(params: { state: ProjectFolders; folder: Folder }): ProjectFolders {
  return {
    ...params.state,
    folders: { ...params.state.folders, [params.folder.id]: params.folder },
  };
}

function withConversation(params: {
  state: ProjectFolders;
  conversationId: ConversationId;
  conversation: FiledConversation;
}): ProjectFolders {
  return {
    ...params.state,
    conversations: {
      ...params.state.conversations,
      [params.conversationId]: params.conversation,
    },
  };
}

/**
 * Creates an open folder, opens its parent and both sections so the new folder is visible.
 * @param params.state - The project to update.
 * @param params.name - The folder name; trimmed, rejected when blank.
 * @param params.parentId - The parent folder, or `null` for a root folder.
 * @param params.newId - The id of the new folder, generated by the caller.
 * @returns The updated project, or `empty-name`, `folder-not-found` or `folder-id-taken`.
 */
export function createFolder(params: {
  state: ProjectFolders;
  name: string;
  parentId: FolderId | null;
  newId: FolderId;
}): OperationResult {
  const { state, parentId, newId } = params;
  const name = params.name.trim();
  if (name === '') {
    return rejected('empty-name');
  }
  const parent = parentId === null ? null : state.folders[parentId];
  if (parent === undefined) {
    return rejected('folder-not-found');
  }
  if (state.folders[newId] !== undefined) {
    return rejected('folder-id-taken');
  }
  const created = withFolder({ state, folder: { id: newId, name, parentId, open: true } });
  const withOpenParent =
    parent === null ? created : withFolder({ state: created, folder: { ...parent, open: true } });
  return accepted({ ...withOpenParent, sectionOpen: { sidebar: true, projectPage: true } });
}

/**
 * Renames a folder.
 * @param params.state - The project to update.
 * @param params.folderId - The folder to rename.
 * @param params.name - The new name; trimmed, rejected when blank.
 * @returns The updated project, or `empty-name` or `folder-not-found`.
 */
export function renameFolder(params: {
  state: ProjectFolders;
  folderId: FolderId;
  name: string;
}): OperationResult {
  const { state, folderId } = params;
  const name = params.name.trim();
  if (name === '') {
    return rejected('empty-name');
  }
  const folder = state.folders[folderId];
  if (folder === undefined) {
    return rejected('folder-not-found');
  }
  return accepted(withFolder({ state, folder: { ...folder, name } }));
}

/**
 * Replaces a folder's emoji and color. A blank or absent emoji and an absent color are removed.
 * @param params.state - The project to update.
 * @param params.folderId - The folder to decorate.
 * @param params.emoji - The emoji to show; trimmed.
 * @param params.color - The color to apply.
 * @returns The updated project, or `folder-not-found`.
 */
export function setFolderAppearance(params: {
  state: ProjectFolders;
  folderId: FolderId;
  emoji?: string;
  color?: string;
}): OperationResult {
  const { state, folderId, color } = params;
  const folder = state.folders[folderId];
  if (folder === undefined) {
    return rejected('folder-not-found');
  }
  const emoji = params.emoji?.trim() ?? '';
  const decorated: Folder = {
    id: folder.id,
    name: folder.name,
    parentId: folder.parentId,
    open: folder.open,
    ...(emoji === '' ? {} : { emoji }),
    ...(color === undefined ? {} : { color }),
  };
  return accepted(withFolder({ state, folder: decorated }));
}

/**
 * Deletes a folder without losing its content: its sub-folders and conversations move up one
 * level, to the deleted folder's parent. Conversations of a deleted root folder become unfiled.
 * @param params.state - The project to update.
 * @param params.folderId - The folder to delete.
 * @returns The updated project, or `folder-not-found`.
 */
export function deleteFolder(params: {
  state: ProjectFolders;
  folderId: FolderId;
}): OperationResult {
  const { state, folderId } = params;
  const deleted = state.folders[folderId];
  if (deleted === undefined) {
    return rejected('folder-not-found');
  }
  const folders: Record<FolderId, Folder> = {};
  for (const [id, folder] of Object.entries(state.folders)) {
    if (id === folderId) {
      continue;
    }
    folders[id] = folder.parentId === folderId ? { ...folder, parentId: deleted.parentId } : folder;
  }
  const conversations: Record<ConversationId, FiledConversation> = {};
  for (const [id, conversation] of Object.entries(state.conversations)) {
    if (conversation.folderId !== folderId) {
      conversations[id] = conversation;
    } else if (deleted.parentId !== null) {
      conversations[id] = { ...conversation, folderId: deleted.parentId };
    }
  }
  return accepted({ ...state, folders, conversations });
}

/**
 * Moves a folder under another folder of the same project, or to the root.
 * @param params.state - The project to update.
 * @param params.folderId - The folder to move.
 * @param params.targetParentId - The new parent, or `null` for the root.
 * @returns The updated project, `folder-not-found`, or `invalid-move` when the target is the
 * folder itself or one of its descendants.
 */
export function moveFolder(params: {
  state: ProjectFolders;
  folderId: FolderId;
  targetParentId: FolderId | null;
}): OperationResult {
  const { state, folderId, targetParentId } = params;
  const folder = state.folders[folderId];
  if (folder === undefined) {
    return rejected('folder-not-found');
  }
  if (targetParentId !== null && state.folders[targetParentId] === undefined) {
    return rejected('folder-not-found');
  }
  if (isInside({ state, candidateId: targetParentId, ancestorId: folderId })) {
    return rejected('invalid-move');
  }
  return accepted(withFolder({ state, folder: { ...folder, parentId: targetParentId } }));
}

function resolveTitle(params: {
  title: string | undefined;
  existing: FiledConversation | undefined;
  fallbackTitle: string;
}): string {
  const given = params.title?.trim() ?? '';
  if (given !== '') {
    return given;
  }
  return params.existing?.title ?? params.fallbackTitle;
}

/**
 * Files a conversation in a folder, or moves it there when it is already filed.
 * @param params.state - The project to update.
 * @param params.conversationId - The conversation to file.
 * @param params.folderId - The destination folder.
 * @param params.title - The conversation title; when blank or absent, the stored title is kept.
 * @param params.fallbackTitle - The title used when neither a title nor a stored one exists.
 * @returns The updated project, or `folder-not-found`.
 */
export function fileConversation(params: {
  state: ProjectFolders;
  conversationId: ConversationId;
  folderId: FolderId;
  title?: string;
  fallbackTitle: string;
}): OperationResult {
  const { state, conversationId, folderId, fallbackTitle } = params;
  if (state.folders[folderId] === undefined) {
    return rejected('folder-not-found');
  }
  const title = resolveTitle({
    title: params.title,
    existing: state.conversations[conversationId],
    fallbackTitle,
  });
  return accepted(withConversation({ state, conversationId, conversation: { title, folderId } }));
}

/**
 * Removes a conversation from its folder.
 * @param params.state - The project to update.
 * @param params.conversationId - The conversation to unfile.
 * @returns The updated project, or `conversation-not-found`.
 */
export function unfileConversation(params: {
  state: ProjectFolders;
  conversationId: ConversationId;
}): OperationResult {
  const { state, conversationId } = params;
  if (state.conversations[conversationId] === undefined) {
    return rejected('conversation-not-found');
  }
  const conversations = Object.fromEntries(
    Object.entries(state.conversations).filter(([id]) => id !== conversationId),
  );
  return accepted({ ...state, conversations });
}

/**
 * Renames a filed conversation.
 * @param params.state - The project to update.
 * @param params.conversationId - The conversation to rename.
 * @param params.title - The new title; trimmed, rejected when blank.
 * @returns The updated project, or `empty-title` or `conversation-not-found`.
 */
export function renameConversation(params: {
  state: ProjectFolders;
  conversationId: ConversationId;
  title: string;
}): OperationResult {
  const { state, conversationId } = params;
  const title = params.title.trim();
  if (title === '') {
    return rejected('empty-title');
  }
  const conversation = state.conversations[conversationId];
  if (conversation === undefined) {
    return rejected('conversation-not-found');
  }
  return accepted(
    withConversation({ state, conversationId, conversation: { ...conversation, title } }),
  );
}

/**
 * Expands a folder; a folder that is already open stays open.
 * @param params.state - The project to update.
 * @param params.folderId - The folder to open.
 * @returns The updated project, or `folder-not-found`.
 */
export function openFolder(params: { state: ProjectFolders; folderId: FolderId }): OperationResult {
  const { state, folderId } = params;
  const folder = state.folders[folderId];
  if (folder === undefined) {
    return rejected('folder-not-found');
  }
  return accepted(withFolder({ state, folder: { ...folder, open: true } }));
}

/**
 * Expands a collapsed folder or collapses an expanded one.
 * @param params.state - The project to update.
 * @param params.folderId - The folder to toggle.
 * @returns The updated project, or `folder-not-found`.
 */
export function toggleFolderOpen(params: {
  state: ProjectFolders;
  folderId: FolderId;
}): OperationResult {
  const { state, folderId } = params;
  const folder = state.folders[folderId];
  if (folder === undefined) {
    return rejected('folder-not-found');
  }
  return accepted(withFolder({ state, folder: { ...folder, open: !folder.open } }));
}

/**
 * Expands or collapses one of the two folder sections (sidebar or project page).
 * @param params.state - The project to update.
 * @param params.section - The section to toggle.
 * @returns The updated project; never rejected.
 */
export function toggleSection(params: {
  state: ProjectFolders;
  section: Section;
}): OperationResult {
  const { state, section } = params;
  return accepted({
    ...state,
    sectionOpen: { ...state.sectionOpen, [section]: !state.sectionOpen[section] },
  });
}
